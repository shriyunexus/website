export default function NavigationDropdown({ items, isOpen, onClose, id }) {
  const menuRef = useRef(null);

  useEffect(() => {
    if (!isOpen) return;

    const handleKeyDown = (e) => {
      if (e.key === 'Escape') {
        onClose();
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!items || items.length === 0) return null;

  return (
    <div
      ref={menuRef}
      id={`dropdown-${id}`}
      className={`nav-dropdown-menu ${isOpen ? 'is-open' : ''}`}
      role="menu"
      aria-label={`${id} submenu`}
    >
      <div className="nav-dropdown-grid">
        {items.map((item, index) => (
          <a
            key={item.href || index}
            href={item.href}
            className="nav-dropdown-item"
            role="menuitem"
            onClick={onClose}
          >
            <div className="nav-dropdown-icon" aria-hidden="true">
              {renderIcon(item.icon)}
            </div>
            <div className="nav-dropdown-content">
              <div className="nav-dropdown-title-row">
                <span className="nav-dropdown-title">{item.title}</span>
                <svg
                  className="dropdown-arrow-icon"
                  width="13"
                  height="13"
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2.2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  aria-hidden="true"
                >
                  <line x1="5" y1="12" x2="19" y2="12" />
                  <polyline points="12 5 19 12 12 19" />
                </svg>
              </div>
              {item.description && (
                <span className="nav-dropdown-desc">{item.description}</span>
              )}
            </div>
          </a>
        ))}
      </div>

      {/* Subtle Bottom Footer Bar */}
      <div className="nav-dropdown-footer">
        <a href={`#${id}`} className="dropdown-footer-link" onClick={onClose}>
          <span>View all {id}</span>
          <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round">
            <polyline points="9 18 15 12 9 6" />
          </svg>
        </a>
      </div>
    </div>
  );
}
